#!/usr/bin/env python3
"""Phase 6: one summary report of the finished database, with pass/fail checks.

Compares the database with the OCEL source, summarizes mapping, flags, civ inference and
the plausibility check, and lists known limitations. Exits with code 1 if a check fails.

Writes reports/validation.md.
Usage: python3 scripts/07_validate.py [--ocel PATH] [--db PATH]
"""
import argparse
import collections
import random
import sqlite3
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from aoe2_plausibility import Checker  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = ROOT / "data/processed/aoe2.db"
DEFAULT_OCEL = ROOT / "data/raw/age_of_empires_ocel2.sqlite"
REPORT = ROOT / "reports/validation.md"
REASONS = ("civ", "age", "prerequisite", "producer", "spending")
LIMITATIONS = [
    "START and COMPLETE times are simulated by the dataset authors from a fixed duration per type (0 s for many). "
    "Only COMMAND (and START for buildings) are real decision times.",
    "Research durations in the log mostly match no rule version; COMPLETE RESEARCH times are unusable.",
    "Age-up commands are missing in many sessions that clearly reach the age; the age estimate falls back to the "
    "first use of an age-gated object.",
    "Celts, Dravidians, Hindustanis (also Romans, Georgians) have no unique unit or tech in the log; their events "
    "are probably mislabeled or dropped, so these civs are rarely or never identified.",
    "Replacement buildings are logged under base names (Folwark as Mill, Fortified Church as Monastery); handled "
    "via data/manual/replacement_equivalents.csv. Mule Cart is not modeled.",
    "Not in the log: civ, map, Elo, match outcome, attacks, deaths, gathered amounts, cancelled production. "
    "Villager counts are 'trained so far'; spending can be overestimated.",
    "Rules are the 2023 tree without civ cost bonuses and without population data. Age-up building rules come "
    "from general game knowledge (data/manual/manual_dependencies.csv); Folwark and Fortified Church counting "
    "toward age-ups is an assumption; Mule Cart, Krepost and Donjon are not modeled as age-up buildings.",
    "The spending check is a loose sanity bound (0.5 resources per villager-second), not an income model.",
    "The 2023 tree lists the Xolotl Warrior for Aztecs, Incas and Mayans at a Stable they do not have.",
]


def md_table(headers, rows):
    def cell(value):
        return "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")
    lines = ["| " + " | ".join(headers) + " |", "|" + " --- |" * len(headers)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def pct(part, whole, digits=1):
    return f"{100 * part / whole:.{digits}f}%" if whole else "n/a"


def main():
    parser = argparse.ArgumentParser(description="Summarize and check the finished database.")
    parser.add_argument("--ocel", type=Path, default=DEFAULT_OCEL)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    args = parser.parse_args()
    started = time.time()
    con = sqlite3.connect(args.db, uri=True)
    con.execute("ATTACH DATABASE ? AS src", (f"file:{args.ocel.resolve()}?mode=ro",))
    q = lambda sql, *a: con.execute(sql, a).fetchall()
    one = lambda sql, *a: con.execute(sql, a).fetchone()[0]
    checks = []
    out = ["# Validation summary (Phase 6)",
           "Generated by `scripts/07_validate.py`. Details: `reports/exploration.md` (sources), `static_data.md` "
           "(rules), `replay_load.md` (events), `civ_inference.md`, `resources.md`."]

    out.append("## Source vs. target")
    rows = [
        ("events", one("SELECT COUNT(*) FROM src.event"), one("SELECT COUNT(*) FROM event")),
        ("event types", one("SELECT COUNT(*) FROM src.event_map_type"), one("SELECT COUNT(DISTINCT ocel_type) FROM event")),
        ("E2O links", one("SELECT COUNT(*) FROM src.event_object"), one("SELECT COUNT(*) FROM event_object_link")),
        ("matches", one("SELECT COUNT(*) FROM src.object WHERE ocel_type='Match'"), one("SELECT COUNT(*) FROM match")),
        ("players", one("SELECT COUNT(*) FROM src.object WHERE ocel_type='Player'"), one("SELECT COUNT(*) FROM player")),
        ("sessions", one("SELECT COUNT(*) FROM src.object WHERE ocel_type='Session'"), one("SELECT COUNT(*) FROM session")),
    ]
    per_type = dict(q("SELECT ocel_type, COUNT(*) FROM src.event GROUP BY 1"))
    target_type = dict(q("SELECT ocel_type, COUNT(*) FROM event GROUP BY 1"))
    differing = sum(1 for t in per_type if per_type[t] != target_type.get(t))
    out.append(md_table(["Item", "Source", "Target", "Equal"],
                        [(n, f"{a:,}", f"{b:,}", "yes" if a == b else "**no**") for n, a, b in rows]))
    out.append(f"Event types with a different count: {differing}.")
    checks += [(f"{n}: source = target", a == b) for n, a, b in rows] + [("all event types equal", differing == 0)]
    out.append("Database tables:\n\n" + md_table(["Table", "Rows"], [
        (t, f"{one(f'SELECT COUNT(*) FROM {t}'):,}") for (t,) in q(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]))
    fk = q("PRAGMA main.foreign_key_check")
    checks.append(("no foreign key violations", not fk))

    out.append("## Game rules and mapping")
    out.append(md_table(["game_object type", "source", "Rows"],
                        q("SELECT type, source, COUNT(*) FROM game_object GROUP BY 1, 2 ORDER BY 1, 2")))
    rows = q("""SELECT action, COUNT(*), SUM(method='exact'), SUM(method='normalized'), SUM(method='manual'),
                SUM(method IS NULL) FROM name_mapping GROUP BY 1 ORDER BY 1""")
    out.append(md_table(["Action", "Log names", "exact", "normalized", "manual", "open"], rows))
    open_names = sum(r[5] for r in rows)
    checks.append(("every log name mapped or decided", open_names == 0))
    unknown = one("SELECT id FROM game_object WHERE type='UNKNOWN'")
    decisions, real = con.execute("""SELECT COUNT(*), SUM(game_object_id IS NOT NULL AND game_object_id <> ?) FROM event
        WHERE (action IN ('QUEUE','RESEARCH') AND phase='COMMAND') OR (action='BUILD' AND phase='START')""",
                                  (unknown,)).fetchone()
    vocab_size, vocab_events = con.execute(
        "SELECT COUNT(DISTINCT game_object_id), COUNT(*) FROM event WHERE in_vocabulary=1").fetchone()
    out.append(f"Player decisions mapped to a real game object: {real:,} of {decisions:,} ({pct(real, decisions, 2)}); "
               f"the rest are the log's placeholder names (`UNKNOWN`). Vocabulary: **{vocab_size}** game objects, "
               f"{vocab_events:,} decision events.")

    out.append("## Session flags")
    flags = ["short_match", "no_commands", "outlier_commands", "has_unmapped_events"]
    out.append(md_table(["Flag", "Sessions"], [(f, one(f"SELECT SUM({f}) FROM session")) for f in flags] +
                        [("any", one("SELECT COUNT(*) FROM session WHERE " + " OR ".join(flags)))]))

    out.append("## Civ inference")
    sizes = collections.Counter()
    for (n,) in q("""SELECT (SELECT COUNT(*) FROM civ_group_member m WHERE m.group_id = s.civ_group_id)
                     FROM session s"""):
        sizes["0" if n == 0 else "1" if n == 1 else "2-10" if n <= 10 else "11+"] += 1
    sessions = one("SELECT COUNT(*) FROM session")
    out.append(md_table(["Candidate civs", "Sessions", "Share"],
                        [(b, sizes[b], pct(sizes[b], sessions)) for b in ("0", "1", "2-10", "11+")]))
    identified = dict(q("""SELECT v.name, COUNT(*) FROM session s JOIN civ_group_member m ON m.group_id = s.civ_group_id
        JOIN civilization v ON v.id = m.civ_id WHERE (SELECT COUNT(*) FROM civ_group_member x WHERE x.group_id =
        s.civ_group_id) = 1 GROUP BY 1"""))
    never = sorted(n for (n,) in q("SELECT name FROM civilization") if n not in identified)
    out.append(f"Civs identified alone at least once: {len(identified)} of 45. Never: {', '.join(never)}.")
    checks.append(("every session has a civ group", one("SELECT COUNT(*) FROM session WHERE civ_group_id IS NULL") == 0))

    out.append("## Resources and age")
    out.append(md_table(["Age", "Sessions reaching it", "Without any logged age command"], [
        (a, one("SELECT COUNT(*) FROM session_age WHERE age=?", a),
         one("SELECT COUNT(*) FROM session_age WHERE age=? AND command_s IS NULL", a)) for a in (2, 3, 4)]))
    checks.append(("one resource snapshot per vocabulary event",
                   one("SELECT COUNT(*) FROM resource_snapshot") == vocab_events))
    settings = dict(q("SELECT key, value FROM setting"))
    out.append("Settings: " + "; ".join(f"`{k}` = {v}" for k, v in sorted(settings.items())) + ".")

    out.append("## Plausibility check")
    checker = Checker(con)
    flagged = {r[0] for r in q("SELECT id FROM session WHERE " + " OR ".join(flags))}
    vocabulary = [r[0] for r in q("SELECT DISTINCT game_object_id FROM event WHERE in_vocabulary=1 ORDER BY 1")]
    rng = random.Random(0)
    real, clean, control = collections.Counter(), collections.Counter(), collections.Counter()
    n_real = n_clean = n_control = 0
    for session, t, o in q("SELECT session_id, time_s, game_object_id FROM event WHERE in_vocabulary=1 ORDER BY session_id, id"):
        reasons = {c for c, _ in checker.check(session, t, o)}
        n_real += 1
        for c in reasons | ({"any"} if reasons else set()):
            real[c] += 1
        if session not in flagged:
            n_clean += 1
            for c in reasons | ({"any"} if reasons else set()):
                clean[c] += 1
        substitute = rng.choice(vocabulary)
        if substitute != o:
            sub = {c for c, _ in checker.check(session, t, substitute)}
            n_control += 1
            for c in sub | ({"any"} if sub else set()):
                control[c] += 1
    out.append(md_table(["Reason", "Real decisions, all sessions", "Real decisions, unflagged sessions",
                         "Random substitutes"],
                        [(r, pct(real[r], n_real, 2), pct(clean[r], n_clean, 2), pct(control[r], n_control, 2))
                         for r in ("any",) + REASONS]))
    out.append("Real decisions should pass, so their flagged share is the false-alarm rate. Random substitutes "
               "(a random vocabulary object at the same session and time) show that the checker catches implausible "
               "actions. Spending alarms concentrate in flagged sessions (outliers, cancelled production).")

    out.append("## Checks")
    out.append(md_table(["Check", "Result"], [(c, "PASS" if ok else "**FAIL**") for c, ok in checks]))
    out.append("## Known limitations")
    out.append("\n".join(f"- {item}" for item in LIMITATIONS))
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n\n".join(out) + "\n")
    con.close()
    failed = [c for c, ok in checks if not ok]
    print(f"wrote {REPORT} in {time.time() - started:.0f}s; {len(checks) - len(failed)} of {len(checks)} checks passed")
    if failed:
        sys.exit("FAILED: " + "; ".join(failed))


if __name__ == "__main__":
    main()
